CREATE TABLE IF NOT EXISTS users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE music_bands ADD COLUMN IF NOT EXISTS owner_login VARCHAR(50);
ALTER TABLE music_bands ADD COLUMN IF NOT EXISTS owner_password_hash VARCHAR(100);

CREATE INDEX IF NOT EXISTS idx_music_bands_owner ON music_bands(owner_login);
